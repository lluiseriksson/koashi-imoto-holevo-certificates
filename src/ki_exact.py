"""Pure-stdlib zero-float exact-Q linear algebra and Koashi-Imoto structure engine.
Aligned with Polloreno (arXiv:2611.33129, Nov 24, 2026)
"A Koashi-Imoto Criterion for Holevo-Rate Visible Compression".

Author: Lluis Eriksson
"""
from __future__ import annotations

from fractions import Fraction
from typing import List, Sequence, Tuple

MatQ = List[List[Fraction]]


def mat_mul(A: MatQ, B: MatQ) -> MatQ:
    m, k, n = len(A), len(A[0]), len(B[0])
    return [
        [sum((A[i][t] * B[t][j] for t in range(k)), Fraction(0, 1)) for j in range(n)]
        for i in range(m)
    ]


def mat_sub(A: MatQ, B: MatQ) -> MatQ:
    return [[A[i][j] - B[i][j] for j in range(len(A[0]))] for i in range(len(A))]


def mat_add(A: MatQ, B: MatQ) -> MatQ:
    return [[A[i][j] + B[i][j] for j in range(len(A[0]))] for i in range(len(A))]


def mat_scale(c: Fraction, A: MatQ) -> MatQ:
    return [[c * x for x in row] for row in A]


def mat_trace(A: MatQ) -> Fraction:
    return sum((A[i][i] for i in range(len(A))), Fraction(0, 1))


def mat_is_symmetric(A: MatQ) -> bool:
    n = len(A)
    for i in range(n):
        if len(A[i]) != n:
            return False
        for j in range(i + 1, n):
            if A[i][j] != A[j][i]:
                return False
    return True


def mat_is_zero(A: MatQ) -> bool:
    return all(x == 0 for row in A for x in row)


def mat_commutator(A: MatQ, B: MatQ) -> MatQ:
    return mat_sub(mat_mul(A, B), mat_mul(B, A))


def commutant_dimension_exact(mats: Sequence[MatQ]) -> int:
    """Exact dimension over Q (equivalently C) of the commutant {X in Q^{d x d} : X A = A X for all A in mats}.
    Uses pure-stdlib exact rational Gaussian elimination (zero floats).
    By Schur's Lemma / Wedderburn-Artin for symmetric matrices, commutant_dim == 1 iff the
    C*-algebra generated by `mats` is irreducible (maximal KI core with trivial redundant factor).
    """
    if not mats:
        return 0
    d = len(mats[0])
    nvars = d * d
    rows: List[List[Fraction]] = []
    for A in mats:
        for i in range(d):
            for j in range(d):
                # (X A - A X)_{i,j} = sum_k X_{i,k} A_{k,j} - sum_k A_{i,k} X_{k,j} = 0
                row = [Fraction(0, 1)] * nvars
                for k in range(d):
                    if A[k][j] != 0:
                        row[i * d + k] += A[k][j]
                    if A[i][k] != 0:
                        row[k * d + j] -= A[i][k]
                if any(v != 0 for v in row):
                    rows.append(row)
    # Exact RREF rank over Q
    rank = 0
    m = len(rows)
    for col in range(nvars):
        piv = None
        for r in range(rank, m):
            if rows[r][col] != 0:
                piv = r
                break
        if piv is None:
            continue
        rows[rank], rows[piv] = rows[piv], rows[rank]
        pv = rows[rank][col]
        piv_row = [x / pv for x in rows[rank]]
        rows[rank] = piv_row
        for r in range(rank + 1, m):
            fac = rows[r][col]
            if fac != 0:
                rows[r] = [rows[r][c] - fac * piv_row[c] for c in range(nvars)]
        rank += 1
        if rank == nvars:
            break
    return nvars - rank


def mat_is_psd_exact(A: MatQ) -> bool:
    """Exact zero-float PSD test for real-symmetric matrix over Q via symmetric Gaussian pivot elimination (LDL^T)."""
    if not mat_is_symmetric(A):
        return False
    n = len(A)
    M = [row[:] for row in A]
    for i in range(n):
        # Find a diagonal pivot among i..n-1; if all diagonals are 0, remaining submatrix must be all 0
        piv = None
        for r in range(i, n):
            if M[r][r] < 0:
                return False
            if M[r][r] > 0:
                piv = r
                break
        if piv is None:
            # All remaining diagonal entries are 0 -> PSD iff all remaining off-diagonal entries are 0
            for r in range(i, n):
                for c in range(i, n):
                    if M[r][c] != 0:
                        return False
            return True
        if piv != i:
            M[i], M[piv] = M[piv], M[i]
            for r in range(n):
                M[r][i], M[r][piv] = M[r][piv], M[r][i]
        d = M[i][i]
        for r in range(i + 1, n):
            factor = M[r][i] / d
            if factor != 0:
                for c in range(i + 1, n):
                    M[r][c] -= factor * M[i][c]
            M[r][i] = Fraction(0, 1)
            M[i][r] = Fraction(0, 1)
    return True


def mat_kron(A: MatQ, B: MatQ) -> MatQ:
    ra, ca = len(A), len(A[0])
    rb, cb = len(B), len(B[0])
    out = [[Fraction(0, 1)] * (ca * cb) for _ in range(ra * rb)]
    for i in range(ra):
        for j in range(ca):
            aij = A[i][j]
            if aij == 0:
                continue
            for r in range(rb):
                for c in range(cb):
                    out[i * rb + r][j * cb + c] = aij * B[r][c]
    return out


def mat_direct_sum(blocks: Sequence[MatQ]) -> MatQ:
    total = sum(len(b) for b in blocks)
    out = [[Fraction(0, 1)] * total for _ in range(total)]
    off = 0
    for b in blocks:
        m = len(b)
        for i in range(m):
            for j in range(m):
                out[off + i][off + j] = b[i][j]
        off += m
    return out


def pure_projector_exact(vec: Sequence[Fraction]) -> MatQ:
    """Exact rank-1 projector |v><v| / <v|v> over Q (zero square roots)."""
    norm_sq = sum((x * x for x in vec), Fraction(0, 1))
    if norm_sq <= 0:
        raise ValueError("Pure state vector must be nonzero")
    return [[(a * b) / norm_sq for b in vec] for a in vec]


def bloch_cross(a: Tuple[Fraction, Fraction, Fraction], b: Tuple[Fraction, Fraction, Fraction]) -> Tuple[Fraction, Fraction, Fraction]:
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def bloch_norm_sq(a: Tuple[Fraction, Fraction, Fraction]) -> Fraction:
    return a[0] * a[0] + a[1] * a[1] + a[2] * a[2]


def fmt_rat(q: Fraction) -> str:
    if q.denominator == 1:
        return str(q.numerator)
    return f"{q.numerator}/{q.denominator}"
